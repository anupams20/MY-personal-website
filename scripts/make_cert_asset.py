# -*- coding: utf-8 -*-
"""Build the view-only certificate asset for /about.

Reads the ORIGINAL scan from OUTSIDE the repo (never commit it),
produces a downscaled, redacted, watermarked JPEG and writes it
base64-embedded into data/cert-data.js (no image URL exists).

Usage:  python scripts/make_cert_asset.py "C:/path/to/graduation_certificate.pdf"
"""
import base64, io, sys
import pymupdf
from PIL import Image, ImageDraw, ImageFilter, ImageFont

SRC = sys.argv[1] if len(sys.argv) > 1 else r"C:\Users\Abhinav PC\Downloads\graduation_certificate.pdf"
OUT = "data/cert-data.js"
TARGET_W = 1000          # readable on a phone, useless for print (~85 dpi on A4)
JPEG_Q = 55

# redaction boxes as fractions of (w, h): serial no (top-left), roll no
# (top-right), and the full signature band at the bottom
REDACT = [
    (0.02, 0.010, 0.48, 0.050),   # serial no.
    (0.52, 0.010, 0.98, 0.050),   # roll no.
    (0.08, 0.830, 0.95, 0.940),   # three signatures (names/titles below stay)
]

doc = pymupdf.open(SRC)
page = doc[0]
zoom = TARGET_W / page.rect.width
pix = page.get_pixmap(matrix=pymupdf.Matrix(zoom, zoom))
img = Image.open(io.BytesIO(pix.tobytes("png"))).convert("RGB")
w, h = img.size

# --- redact: strong pixelate + blur so nothing is recoverable ---
for fx1, fy1, fx2, fy2 in REDACT:
    box = (int(fx1 * w), int(fy1 * h), int(fx2 * w), int(fy2 * h))
    region = img.crop(box)
    region = region.resize((max(1, region.width // 24), max(1, region.height // 24)), Image.BILINEAR)
    region = region.resize((box[2] - box[0], box[3] - box[1]), Image.NEAREST)
    region = region.filter(ImageFilter.GaussianBlur(6))
    img.paste(region, box)

# --- tiled diagonal watermark, baked into the pixels ---
try:
    font = ImageFont.truetype("arial.ttf", 22)
except OSError:
    font = ImageFont.load_default()
text = "VERIFICATION ONLY · anupamwebworks.com · Oct 2026"
tw = int(ImageDraw.Draw(Image.new("RGB", (1, 1))).textlength(text, font=font))
tile = Image.new("RGBA", (tw + 40, 70), (0, 0, 0, 0))
ImageDraw.Draw(tile).text((20, 20), text, font=font, fill=(11, 59, 60, 84))
tile = tile.rotate(27, expand=True)
layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
for row, y in enumerate(range(-tile.height, h, 190)):
    for x in range(-tile.width + (row % 2) * 170, w, tile.width + 60):
        layer.alpha_composite(tile, (x, y))
img = Image.alpha_composite(img.convert("RGBA"), layer).convert("RGB")

buf = io.BytesIO()
img.save(buf, "JPEG", quality=JPEG_Q, optimize=True)
b64 = base64.b64encode(buf.getvalue()).decode("ascii")
with io.open(OUT, "w", encoding="utf-8") as f:
    f.write("/* Generated by scripts/make_cert_asset.py — downscaled, redacted,\n"
            "   watermarked copy for the view-only /about viewer. The original\n"
            "   scan lives OUTSIDE the repo and must never be committed. */\n"
            "window.CERT_DATA={w:%d,h:%d,src:\"data:image/jpeg;base64,%s\"};\n" % (w, h, b64))
print("wrote %s  (%d x %d, %.0f KB)" % (OUT, w, h, len(b64) * 3 / 4 / 1024))
